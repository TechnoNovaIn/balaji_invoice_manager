"""
Balaji InvoiceHub - Tally Structured Excel Exporter (Phase 6)
Generates audit-compliant, structured Excel workbooks for Tally accounting import.
"""
import io
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter
from django.utils import timezone
from .models import TallyLedgerMapping, ExportAuditLog
from .export_security import safe_xlsx_value, sanitize_spreadsheet_text


def generate_tally_structured_excel(queryset, user=None, filter_info=None):
    """
    Exports invoices to a professional Excel workbook formatted for Tally purchase voucher entry.
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Tally Purchase Vouchers"

    # Style constants
    FONT_TITLE = Font(name="Calibri", size=14, bold=True, color="1E3A8A")
    FONT_SUBTITLE = Font(name="Calibri", size=10, italic=True, color="475569")
    FONT_HEADER = Font(name="Calibri", size=10, bold=True, color="FFFFFF")
    FONT_DATA = Font(name="Calibri", size=10)
    FONT_TOTAL = Font(name="Calibri", size=10, bold=True, color="000000")

    FILL_HEADER = PatternFill(start_color="1E3A8A", end_color="1E3A8A", fill_type="solid")
    FILL_ZEBRA = PatternFill(start_color="F8FAFC", end_color="F8FAFC", fill_type="solid")
    FILL_TOTAL = PatternFill(start_color="E2E8F0", end_color="E2E8F0", fill_type="solid")

    BORDER_THIN = Border(
        left=Side(style='thin', color='CBD5E1'),
        right=Side(style='thin', color='CBD5E1'),
        top=Side(style='thin', color='CBD5E1'),
        bottom=Side(style='thin', color='CBD5E1')
    )
    BORDER_DOUBLE_BOTTOM = Border(
        left=Side(style='thin', color='CBD5E1'),
        right=Side(style='thin', color='CBD5E1'),
        top=Side(style='thin', color='CBD5E1'),
        bottom=Side(style='double', color='000000')
    )

    # Title Block
    ws['A1'] = "BALAJI TRANSPORTS — TALLY PURCHASE VOUCHERS IMPORT"
    ws['A1'].font = FONT_TITLE
    ws['A2'] = f"Generated by: {user.get_full_name() or user.username if user else 'System'} on {timezone.now().strftime('%d-%b-%Y %I:%M %p')} | GSTIN: 29AAWFB0395H1ZX"
    ws['A2'].font = FONT_SUBTITLE
    ws.row_dimensions[1].height = 24
    ws.row_dimensions[2].height = 18

    # Headers
    headers = [
        "Voucher Date",
        "Voucher Type",
        "Supplier / Party Name",
        "Supplier GSTIN",
        "Supplier State",
        "Supplier Bill No",
        "Bill Date",
        "Purchase Expense Ledger",
        "Taxable Amount (₹)",
        "CGST Ledger",
        "CGST Amount (₹)",
        "SGST Ledger",
        "SGST Amount (₹)",
        "IGST Ledger",
        "IGST Amount (₹)",
        "Total Voucher Value (₹)",
        "HSN / SAC",
        "Narration",
        "Tracking ID",
        "Tally Status",
        "Verification Status"
    ]

    header_row = 4
    ws.row_dimensions[header_row].height = 26

    for col_idx, header_text in enumerate(headers, 1):
        cell = ws.cell(row=header_row, column=col_idx, value=header_text)
        cell.font = FONT_HEADER
        cell.fill = FILL_HEADER
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER_THIN

    # Build ledger mappings cache
    mappings = {m.tally_expense_ledger.lower(): m for m in TallyLedgerMapping.objects.filter(is_active=True)}

    current_row = 5
    total_taxable = 0.0
    total_amount = 0.0

    for idx, sub in enumerate(queryset, 1):
        # Format date
        v_date = sub.invoice_date.strftime('%d-%m-%Y') if sub.invoice_date else sub.created_at.strftime('%d-%m-%Y')
        b_date = sub.invoice_date.strftime('%d-%m-%Y') if sub.invoice_date else ''
        
        # State lookup
        state = ""
        if sub.party_gstin and len(sub.party_gstin) >= 2:
            state_code = sub.party_gstin[:2]
            from .vendor_directory import STATE_CODE_MAP
            state = STATE_CODE_MAP.get(state_code, f"State Code {state_code}")

        # Ledger assignment
        ledger = sub.expense_ledger or "Purchase Spares & Consumables"
        mapping = mappings.get(ledger.lower())
        cgst_ledger = mapping.cgst_ledger if mapping else "Input CGST"
        sgst_ledger = mapping.sgst_ledger if mapping else "Input SGST"
        igst_ledger = mapping.igst_ledger if mapping else "Input IGST"

        taxable = float(sub.taxable_amount)
        cgst = float(sub.cgst_amount)
        sgst = float(sub.sgst_amount)
        igst = float(sub.igst_amount)
        total = float(sub.total_amount)

        total_taxable += taxable
        total_amount += total

        narration = f"Being purchase of {ledger} vide bill #{sub.invoice_number or sub.submission_id}. Captured by {sub.employee.get_full_name() or sub.employee.username}. Ref: {sub.submission_id}. {sub.remarks}".strip()

        row_data = [
            v_date,
            "Purchase",
            sub.party_name or "Unregistered Vendor",
            sub.party_gstin or "",
            state,
            sub.invoice_number or sub.submission_id,
            b_date,
            ledger,
            taxable,
            cgst_ledger if cgst > 0 else "",
            cgst,
            sgst_ledger if sgst > 0 else "",
            sgst,
            igst_ledger if igst > 0 else "",
            igst,
            total,
            sub.hsn_sac_code or "",
            narration,
            sub.submission_id,
            "Entered in Tally" if sub.is_entered_in_tally else "Pending Tally",
            sub.get_status_display()
        ]

        ws.row_dimensions[current_row].height = 20
        fill_color = FILL_ZEBRA if idx % 2 == 0 else PatternFill(fill_type=None)

        for col_idx, val in enumerate(row_data, 1):
            cell = ws.cell(row=current_row, column=col_idx, value=safe_xlsx_value(val))
            cell.font = FONT_DATA
            cell.border = BORDER_THIN
            if fill_color.fill_type:
                cell.fill = fill_color

            # Numeric formatting for currency columns
            if col_idx in [9, 11, 13, 15, 16]:
                cell.number_format = '#,##0.00'
                cell.alignment = Alignment(horizontal="right", vertical="center")
            elif col_idx in [1, 2, 4, 7, 17, 19, 20, 21]:
                cell.alignment = Alignment(horizontal="center", vertical="center")
            else:
                cell.alignment = Alignment(horizontal="left", vertical="center")

        current_row += 1

    # Totals Row
    ws.row_dimensions[current_row].height = 22
    for c in range(1, len(headers) + 1):
        cell = ws.cell(row=current_row, column=c)
        cell.font = FONT_TOTAL
        cell.fill = FILL_TOTAL
        cell.border = BORDER_DOUBLE_BOTTOM

    ws.cell(row=current_row, column=8, value="TOTAL:")
    ws.cell(row=current_row, column=8).alignment = Alignment(horizontal="right", vertical="center")

    for col_idx in [9, 11, 13, 15, 16]:
        col_letter = get_column_letter(col_idx)
        cell = ws.cell(row=current_row, column=col_idx)
        if current_row > 5:
            cell.value = f"=SUM({col_letter}5:{col_letter}{current_row - 1})"
        else:
            cell.value = 0.00
        cell.number_format = '#,##0.00'
        cell.alignment = Alignment(horizontal="right", vertical="center")

    # Auto-fit column widths
    for col in ws.columns:
        max_len = 0
        col_letter = get_column_letter(col[0].column)
        for cell in col:
            # Skip title row from width calculation
            if cell.row < 4:
                continue
            val_str = str(cell.value or '')
            if len(val_str) > max_len:
                max_len = len(val_str)
        ws.column_dimensions[col_letter].width = max(max_len + 3, 12)

    # Ensure narration column is wider
    ws.column_dimensions['R'].width = 35

    buffer = io.BytesIO()
    wb.save(buffer)
    buffer.seek(0)

    # Log export in audit history
    if user:
        ExportAuditLog.objects.create(
            export_type='TALLY_EXCEL',
            exported_by=user,
            record_count=queryset.count(),
            total_taxable=total_taxable,
            total_amount=total_amount,
            filename=f"tally_vouchers_{timezone.now().strftime('%Y%m%d_%H%M')}.xlsx",
            filters_applied=filter_info or {}
        )

    return buffer

